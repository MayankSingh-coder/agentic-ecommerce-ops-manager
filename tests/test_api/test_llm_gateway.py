def test_llm_gateway_uses_cache_when_prompt_policy_enables_it(tmp_path):
    prompt_dir = tmp_path / "prompts"
    prompt_dir.mkdir()
    (prompt_dir / "cached_prompt.yaml").write_text(
        """
prompt_id: cached_prompt_v1
agent: marketing
provider: litellm
model: openai/gpt-4.1-mini
system_prompt: Generate cached copy.
temperature: 0.0
max_tokens: 50
input_schema: TestInput.v1
output_schema: string
allowed_for_agents:
  - marketing
fallback: null
cache_policy:
  enabled: true
  ttl_seconds: 60
""",
        encoding="utf-8",
    )
    call_count = 0

    def handler(request: httpx.Request) -> httpx.Response:
        nonlocal call_count
        call_count += 1
        return httpx.Response(
            200,
            json={
                "choices": [{"message": {"content": f"proxy-call-{call_count}"}}],
                "usage": {"total_tokens": 10},
            },
        )

    gateway = LLMGateway(
        prompt_registry=PromptRegistry(prompt_dir),
        http_client=httpx.Client(transport=httpx.MockTransport(handler)),
        cache=InMemoryLLMCache(),
    )

    first = gateway.generate_text(
        prompt_id="cached_prompt_v1",
        agent="marketing",
        input_data={"sku": "SKU-1003"},
    )
    second = gateway.generate_text(
        prompt_id="cached_prompt_v1",
        agent="marketing",
        input_data={"sku": "SKU-1003"},
    )

    assert first.output == "proxy-call-1"
    assert first.cached is False
    assert second.output == "proxy-call-1"
    assert second.cached is True
    assert call_count == 1


def test_llm_gateway_bypasses_cache_when_policy_disables_it(tmp_path):
    prompt_dir = tmp_path / "prompts"
    prompt_dir.mkdir()
    (prompt_dir / "uncached_prompt.yaml").write_text(
        """
prompt_id: uncached_prompt_v1
agent: marketing
provider: litellm
model: openai/gpt-4.1-mini
system_prompt: Generate uncached copy.
temperature: 0.0
max_tokens: 50
input_schema: TestInput.v1
output_schema: string
allowed_for_agents:
  - marketing
fallback: null
cache_policy:
  enabled: false
""",
        encoding="utf-8",
    )
    call_count = 0

    def handler(request: httpx.Request) -> httpx.Response:
        nonlocal call_count
        call_count += 1
        return httpx.Response(
            200,
            json={"choices": [{"message": {"content": f"proxy-call-{call_count}"}}]},
        )

    gateway = LLMGateway(
        prompt_registry=PromptRegistry(prompt_dir),
        http_client=httpx.Client(transport=httpx.MockTransport(handler)),
        cache=InMemoryLLMCache(),
    )

    first = gateway.generate_text("uncached_prompt_v1", "marketing", {"sku": "SKU-1003"})
    second = gateway.generate_text("uncached_prompt_v1", "marketing", {"sku": "SKU-1003"})

    assert first.output == "proxy-call-1"
    assert second.output == "proxy-call-2"
    assert first.cached is False
    assert second.cached is False
    assert call_count == 2


def test_in_memory_llm_cache_expires_entries():
    cache = InMemoryLLMCache()
    response = LLMGateway().generate_text(
        prompt_id="marketing_draft_v1",
        agent="marketing",
        input_data={"product_name": "Trail Runner", "offer": "10% off"},
    )

    cache.set("cache-key", response, ttl_seconds=0)
    time.sleep(0.001)

    assert cache.get("cache-key") is None
