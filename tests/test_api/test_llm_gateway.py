def test_llm_gateway_calls_litellm_proxy_with_openai_compatible_payload(tmp_path):
    prompt_dir = tmp_path / "prompts"
    prompt_dir.mkdir()
    (prompt_dir / "test_prompt.yaml").write_text(
        """
prompt_id: test_litellm_prompt_v1
agent: marketing
provider: litellm
model: gemini/gemini-1.5-flash
system_prompt: Generate campaign copy from JSON.
temperature: 0.2
max_tokens: 200
input_schema: TestInput.v1
output_schema: string
allowed_for_agents:
  - marketing
fallback: null
cache_policy:
  enabled: false
""",
        encoding="utf-8",
    )
    captured_payload = {}

    def handler(request: httpx.Request) -> httpx.Response:
        captured_payload.update(json.loads(request.content.decode("utf-8")))
        return httpx.Response(
            200,
            json={
                "choices": [
                    {
                        "message": {
                            "content": "Generated by LiteLLM proxy.",
                        }
                    }
                ],
                "usage": {
                    "prompt_tokens": 12,
                    "completion_tokens": 5,
                    "total_tokens": 17,
                },
            },
        )

    gateway = LLMGateway(
        prompt_registry=PromptRegistry(prompt_dir),
        http_client=httpx.Client(transport=httpx.MockTransport(handler)),
        provider_override="prompt",
    )

    response = gateway.generate_text(
        prompt_id="test_litellm_prompt_v1",
        agent="marketing",
        input_data={"sku": "SKU-1003"},
    )

    assert response.provider == "litellm"
    assert response.model == "gemini/gemini-1.5-flash"
    assert response.output == "Generated by LiteLLM proxy."
    assert response.usage["total_tokens"] == 17
    assert captured_payload["model"] == "gemini/gemini-1.5-flash"
    assert captured_payload["messages"][0]["role"] == "system"
    assert captured_payload["messages"][1]["role"] == "user"
    assert '"sku": "SKU-1003"' in captured_payload["messages"][1]["content"]


